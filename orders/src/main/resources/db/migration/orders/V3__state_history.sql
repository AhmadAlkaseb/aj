CREATE TABLE state_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 aggregate_guid uuid NOT NULL,
 old_status varchar(40), new_status varchar(40) NOT NULL,
 correlation_id varchar(100), recorded_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX state_audit_aggregate ON state_audit(aggregate_guid,id);
CREATE TABLE order_confirmations (
 order_guid uuid PRIMARY KEY REFERENCES orders(guid),
 document bytea NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
